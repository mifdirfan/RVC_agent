"""Human evaluation storage and the test_results.md report.

simulator/results/evaluations.json holds one record per scenario id (built-in or
custom) as entered by the human evaluator in the simulator. This module never
creates a verdict; scenarios without a record are reported as Pending.
Standard library only.
"""
import datetime
import json
import os

SIM_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SIM_DIR)
RESULTS_DIR = os.path.join(SIM_DIR, "results")
EVAL_FILE = os.path.join(RESULTS_DIR, "evaluations.json")
REPORT = os.path.join(ROOT, "artifacts", "SystemTest", "test_results.md")
VERDICTS = ("PASS", "FAIL", "INCONCLUSIVE")


def load_evaluations():
    try:
        with open(EVAL_FILE, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return {}


def save_evaluation(record, trace):
    """Stores a human evaluation and its trace. Returns the stored record."""
    sid = str(record.get("scenario_id", "")).strip()
    verdict = str(record.get("result", "")).upper()
    if not sid or not all(c.isalnum() or c in "-_" for c in sid):
        raise ValueError("invalid scenario_id")
    if verdict not in VERDICTS:
        raise ValueError("result must be PASS, FAIL or INCONCLUSIVE")
    os.makedirs(os.path.join(RESULTS_DIR, "traces"), exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
    trace_rel = None
    if trace is not None:
        trace_rel = f"results/traces/{sid}_{stamp}.json"
        with open(os.path.join(SIM_DIR, trace_rel), "w", encoding="utf-8") as f:
            json.dump(trace, f)
    stored = {
        "scenario_id": sid,
        "scenario_name": str(record.get("scenario_name", ""))[:200],
        "result": verdict,
        "evaluator": str(record.get("evaluator", ""))[:100],
        "observations": str(record.get("observations", ""))[:4000],
        "related_ticks": str(record.get("related_ticks", ""))[:200],
        "trace_source": str(record.get("trace_source", ""))[:50],
        "custom": bool(record.get("custom", False)),
        "recorded_at": datetime.datetime.now().isoformat(timespec="seconds"),
        "trace_file": "simulator/" + trace_rel if trace_rel else None,
    }
    evals = load_evaluations()
    history = evals.get(sid, {}).get("history", [])
    if sid in evals:
        prev = dict(evals[sid])
        prev.pop("history", None)
        history.append(prev)
    stored["history"] = history
    evals[sid] = stored
    os.makedirs(RESULTS_DIR, exist_ok=True)
    with open(EVAL_FILE, "w", encoding="utf-8") as f:
        json.dump(evals, f, indent=2)
    write_report()
    return stored


def _md(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def write_report():
    import sys
    sys.path.insert(0, SIM_DIR)
    from scenario_defs import SCENARIOS

    evals = load_evaluations()
    builtin = [s["id"] for s in SCENARIOS]
    names = {s["id"]: s["name"] for s in SCENARIOS}
    custom = sorted(k for k in evals if k not in builtin)
    counts = {v: 0 for v in VERDICTS}
    for k in builtin + custom:
        if k in evals:
            counts[evals[k]["result"]] += 1
    pending = len(builtin) - sum(1 for k in builtin if k in evals)

    L = []
    a = L.append
    a("# System Test Results")
    a("")
    a("Generated by `simulator/results_report.py` from `simulator/results/evaluations.json`. Updated automatically each time an evaluator "
      "presses **Save evaluation** in the simulator. Verdicts are assigned by human evaluators only; the simulator assigns none.")
    a("")
    a(f"Last generated: {datetime.datetime.now().isoformat(timespec='seconds')}")
    a("")
    a("## 1. Summary")
    a("")
    a("| Built-in scenarios | PASS | FAIL | INCONCLUSIVE | Pending | Custom maps evaluated |")
    a("|---|---|---|---|---|---|")
    a(f"| {len(builtin)} | {counts['PASS']} | {counts['FAIL']} | {counts['INCONCLUSIVE']} | {pending} | {len(custom)} |")
    a("")
    a("## 2. Results per Scenario")
    a("")
    a("| Scenario | Name | Human Result | Evaluator | Related Ticks | Recorded | Trace |")
    a("|---|---|---|---|---|---|---|")
    for k in builtin + custom:
        e = evals.get(k)
        nm = names.get(k, e.get("scenario_name", "") if e else "")
        if e:
            a(f"| {k} | {_md(nm)} | {e['result']} | {_md(e['evaluator'])} | {_md(e['related_ticks'])} | {e['recorded_at']} | "
              f"{e['trace_file'] or '-'} |")
        else:
            a(f"| {k} | {_md(nm)} | Pending | | | | simulator/traces/{k}.json (pre-generated) |")
    a("")
    a("## 3. Observations")
    a("")
    any_obs = False
    for k in builtin + custom:
        e = evals.get(k)
        if e and e.get("observations"):
            any_obs = True
            a(f"### {k} - {e['result']}")
            a("")
            a(e["observations"])
            a("")
            if e.get("history"):
                a(f"Earlier evaluations: {len(e['history'])} (kept in evaluations.json).")
                a("")
    if not any_obs:
        a("No observations recorded yet.")
        a("")
    a("## 4. Execution Traces")
    a("")
    a("- Pre-generated traces of every built-in scenario: `simulator/traces/ST-xx.json` (produced by the real C controller via `sim_runner`).")
    a("- Traces of evaluated runs: `simulator/results/traces/<scenario>_<timestamp>.json`.")
    a("")
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(L))


if __name__ == "__main__":
    write_report()
    print(REPORT)
